import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdtemp,rm } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import PDFDocument from 'pdfkit';
const temp=await mkdtemp(path.join(os.tmpdir(),'researchbridge-browser-'));
process.env.DEMO_MODE='true';process.env.DATA_DIR=temp;
const {start}=await import('../server.js');
const server=await start(0);if(!server.listening)await new Promise(r=>server.once('listening',r));
let browser;
try{
  browser=await chromium.launch({...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{}),headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:'+server.address().port);
  await page.getByText('Simulated demo',{exact:true}).waitFor();
  await page.screenshot({path:path.join(temp,'desktop.png')});
  await page.getByText('Start with your course material',{exact:true}).click();
  const buffer=await new Promise(resolve=>{const pdf=new PDFDocument();const chunks=[];pdf.on('data',c=>chunks.push(c));pdf.on('end',()=>resolve(Buffer.concat(chunks)));pdf.text('Distributed systems use logical clocks and event ordering. A send event happens before the corresponding receive event. Algorithms and formal reasoning rely on explicit assumptions. Proof techniques help demonstrate correctness of a theorem. Computer networks carry messages.');pdf.end();});
  await page.locator('#pdf-file').setInputFiles({name:'course.pdf',mimeType:'application/pdf',buffer});
  await page.locator('#consent').check();await page.getByRole('button',{name:'Explore my course'}).click();
  await page.locator('#interview-controls').waitFor({state:'visible'});
  assert.match(await page.locator('.message-text').last().innerText(),/bachelor/);
  assert.equal(await page.locator('#plan-view .day-card').count(),0);
  const send=async text=>{await page.locator('#message').fill(text);await page.locator('#send').click();await page.locator('#send').waitFor({state:'visible'});await page.waitForFunction(()=>!document.querySelector('#busy-status'));};
  await send('Telecommunications Engineering');
  assert.match(await page.locator('.message-text').last().innerText(),/Telecommunications Engineering/);
  await page.getByRole('button',{name:'Skip this question',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('#skip-question').disabled);
  assert.match(await page.locator('.message-text').last().innerText(),/confident/);
  await send('I have low confidence and struggle with proofs.');
  await page.getByRole('button',{name:'Generate my plan now'}).click();
  await page.getByRole('button',{name:'Generate My Bridge Plan'}).waitFor();
  await page.getByRole('button',{name:'Edit My Background'}).click();
  await page.locator('#profile-bachelor_major').fill('Telecommunications Engineering — updated');
  await page.locator('#profile-previous_courses').fill('Computer networks');
  await page.locator('#profile-learning_preferences').fill('Visual examples, 25 minutes daily');
  await page.getByRole('button',{name:'Save & review my profile'}).click();
  await page.getByRole('button',{name:'Generate My Bridge Plan'}).waitFor();
  assert.match(await page.locator('.profile-summary').innerText(),/updated/);
  await page.getByRole('button',{name:'Generate My Bridge Plan'}).click();
  await page.locator('#plan-view').waitFor({state:'visible'});
  assert.equal(await page.locator('.day-card').count(),7);
  await page.locator('.day-card input').first().check();
  await page.waitForFunction(()=>document.querySelectorAll('.day-card.completed').length===1);
  await page.locator('#plan-view .citation').first().click();await page.locator('#source-dialog').waitFor({state:'visible'});
  assert.ok(await page.locator('#source-content mark').count());await page.locator('#source-dialog .close-dialog').click();
  await page.getByRole('button',{name:'Find YouTube resources'}).click();await page.locator('a.resource').first().waitFor();
  assert.match(await page.locator('a.resource').first().getAttribute('href'),/^https:\/\/www.youtube.com\/results\?/);
  await page.getByRole('button',{name:'Try a readiness check',exact:true}).click();await page.locator('#chat-view').waitFor({state:'visible'});
  await send('The claim depends on its stated assumptions.');
  await page.waitForFunction(()=>document.querySelector('#conversation').innerText.includes('NOT been graded'));
  await page.locator('#open-simplifier').click();await page.locator('#passage').fill('A send event happens before the corresponding receive event.');
  await page.getByRole('button',{name:'Help me understand'}).click();await page.getByRole('heading',{name:'Back to academic language',exact:true}).waitFor();
  await page.locator('#simplify-dialog .close-dialog').click();
  await page.locator('[data-view="progress"]').click();assert.match(await page.locator('#progress-view').innerText(),/SIMULATED · UNGRADED/);
  await page.reload();await page.getByText('Simulated demo',{exact:true}).waitFor();await page.locator('[data-view="plan"]').click();assert.equal(await page.locator('.day-card.completed').count(),1);
  await page.screenshot({path:'/tmp/researchbridge-plan.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});await page.waitForTimeout(200);assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.locator('#mobile-menu').click();await page.locator('[data-view="chat"]').click();await page.waitForTimeout(200);
  assert.equal(await page.locator('#sidebar').evaluate(e=>e.getBoundingClientRect().right<=1),true);
  await page.screenshot({path:'/tmp/researchbridge-mobile-chat.png'});
  await page.locator('#mobile-menu').click();await page.locator('#delete-session').click();await page.locator('#confirm-reset').click();await page.locator('.welcome').waitFor();
  await page.locator('#mobile-menu').click(); // close menu after reset if it remained open
  await page.locator('main').click({position:{x:350,y:150}});await page.waitForTimeout(200);
  await page.screenshot({path:'/tmp/researchbridge-mobile.png'});
  assert.deepEqual(errors,[]);
  console.log('PASS: desktop + mobile browser flow; upload, interview, skip, edit, confirm, seven-day plan, completion, PDF citations, resources, diagnostics, simplification, reload persistence, reset. No browser exceptions or horizontal overflow.');
}finally{
  if(browser)await browser.close();server.closeAllConnections();await new Promise(r=>server.close(r));await rm(temp,{recursive:true,force:true});
}
